/** Fills {partner}, {partner2}, {customer}, {store} in every text of an incident. */
export function personalize(incident, names) {
  const fill = (s) =>
    typeof s === 'string'
      ? s
          .replaceAll('{partner2}', names.partner2)
          .replaceAll('{partner}', names.partner)
          .replaceAll('{customer}', names.customer)
          .replaceAll('{store}', names.store)
      : s
  return {
    ...incident,
    title: fill(incident.title),
    text: fill(incident.text),
    choices: incident.choices.map((c) => ({
      ...c,
      label: fill(c.label),
      outcome: fill(c.outcome),
      chance: c.chance
        ? { ...c.chance, success: { ...c.chance.success, text: fill(c.chance.success.text) }, fail: { ...c.chance.fail, text: fill(c.chance.fail.text) } }
        : undefined,
      later: (c.later || []).map((l) => ({ ...l, text: fill(l.text) })),
    })),
    timeout: { ...incident.timeout, outcome: fill(incident.timeout.outcome) },
  }
}
